def haversine_km(lat1, lon1, lat2, lon2):
    """คำนวณระยะทางเส้นตรงระหว่างสองพิกัด (กม.) ด้วยสูตร Haversine"""
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlmb = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dlmb / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


def main():
    rows = []
    for name, province, ptype, lat, lon in PLACES:
        cost_lo, cost_hi = COST_RANGE[ptype]
        dur_lo, dur_hi = DURATION_RANGE[ptype]

        cost = int(np.random.uniform(cost_lo, cost_hi))
        duration_days = round(float(np.random.uniform(dur_lo, dur_hi)), 2)
        review_score = int(np.random.uniform(55, 98))       # คะแนนรีวิว 0-100
        popularity = int(np.random.uniform(40, 100))        # ความนิยม 0-100

        # ระยะทางจริง: คำนวณจากพิกัดสถานที่ เทียบกับพิกัดตัวเมือง/ศูนย์กลางจังหวัด
        center_lat, center_lon = PROVINCE_CENTER[province]
        distance_km = round(haversine_km(lat, lon, center_lat, center_lon), 1)

        rows.append({
            "name": name,
            "province": province,
            "type": ptype,
            "lat": lat,
            "lon": lon,
            "cost": cost,
            "duration_days": duration_days,
            "review_score": review_score,
            "distance_km": distance_km,
            "popularity": popularity,
            "activities": ",".join(ACTIVITIES_BY_TYPE[ptype]),
            "season": SEASON_BY_TYPE[ptype],
            "travel_style": ",".join(TRAVEL_STYLE_BY_TYPE[ptype]),
        })

    df = pd.DataFrame(rows)
    df.to_csv("travel_data.csv", index=False, encoding="utf-8-sig")
    print(f"สร้างข้อมูลสำเร็จ: {len(df)} แถว -> travel_data.csv")


if __name__ == "__main__":
    main()
